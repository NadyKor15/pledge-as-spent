// Renders the receipt sets to PNG with ground truth.
//   npx tsx tools/receipts/generate.ts [--set v1|adversarial|hero|holdout|holdout2|all] [--only <id>] [--out <dir>]
// Without --out the files go to eval/receipts/ and recorded.json is rebuilt from every truth file there.

import { chromium } from "@playwright/test";
import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { receiptKey, type Recordings } from "../../src/receipts/recorded";
import { renderHtml } from "./render";
import { FLORIDA, HERO_PLEDGES_JPY, SCENARIOS } from "./scenario";
import { buildAdversarial, buildFlorida, buildHero, buildHoldout, buildHoldout2, buildV1 } from "./sets";
import { specToClassifications, specToReceipt, type Bbox, type ReceiptSpec } from "./spec";
import { Truth } from "./truth";

const ROOT = path.resolve(import.meta.dirname, "../..");
const args = process.argv.slice(2);
const arg = (name: string) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : undefined;
};

export function allSpecs(): ReceiptSpec[] {
  const v1 = buildV1();
  return [...v1, ...buildAdversarial(v1), buildHero(), ...buildFlorida()];
}

export async function render(page: import("@playwright/test").Page, spec: ReceiptSpec) {
  await page.setViewportSize({ width: 1600, height: 3400 });
  await page.setContent(renderHtml(spec), { waitUntil: "load" });
  await page.evaluate(() => document.fonts.ready);
  const size: { width: number; height: number } = await page.evaluate((p) => (window as never as { __photo: (p: unknown) => { width: number; height: number } }).__photo(p), spec.photo);
  await page.setViewportSize(size);
  const raw: Record<string, NonNullable<Bbox>> = await page.evaluate(() => (window as never as { __piiBoxes: () => Record<string, NonNullable<Bbox>> }).__piiBoxes());
  const round = (n: number) => Math.round(n * 10000) / 10000;
  const boxes: Bbox[] = spec.pii.map((_, i) => {
    const b = raw[String(i)];
    if (!b) throw new Error(`${spec.id}: personal data #${i} (${spec.pii[i].kind}) is not on the page`);
    if (b.x < 0 || b.y < 0 || b.x + b.w > 1 || b.y + b.h > 1) throw new Error(`${spec.id}: personal data #${i} lies outside the photo`);
    return { x: round(b.x), y: round(b.y), w: round(b.w), h: round(b.h) };
  });
  const png = await page.locator(".stage").screenshot({ type: "png" });
  return { png, size, boxes };
}

function heroReadme(spec: ReceiptSpec): string {
  const sc = SCENARIOS.ja;
  const yen = (n: number) => `¥${n.toLocaleString("en-US")}`;
  const rows = spec.lines.map((l, i) => {
    const lb = l.label;
    const need = lb.needId ? `${lb.needId} x${lb.needQty}` : "-";
    const verdict = lb.verdict === "eligible" ? "eligible" : `rejected (${lb.ruleCode})`;
    return `| ${i + 1} | ${l.name.join(" / ")} | ${l.translationEn} | ${l.qty ?? ""} | ${l.taxRateBp === null ? "-" : l.taxRateBp / 100 + "%"} | ${yen(l.amountMinor)} | ${verdict} | ${need} |`;
  });
  const per = (id: string) => ({
    qty: spec.lines.filter((l) => l.label.needId === id).reduce((s, l) => s + (l.label.needQty ?? 0), 0),
    yen: spec.lines.filter((l) => l.label.needId === id).reduce((s, l) => s + l.amountMinor, 0),
  });
  const needs = sc.needs.slice(0, 3).map((n) => {
    const p = per(n.id);
    const pledge = HERO_PLEDGES_JPY[n.id as keyof typeof HERO_PLEDGES_JPY];
    return `| ${n.label} (${n.unit}, ${n.qtyNeeded} needed) | ${p.qty} | ${yen(p.yen)} | ${yen(pledge)} | ${yen(2 * pledge)} | ${p.yen <= 2 * pledge ? "yes" : "NO"} |`;
  });
  return `# Hero receipt (${spec.id})

Japanese, tax included (内税), card payment, fictional store ${spec.store.name} ${spec.store.branch}, ${spec.purchasedAt}.
Generated by \`tools/receipts/generate.ts\` (seed ${spec.seed}); this table is written from the same spec as the image and the truth file.

| # | Printed | English | Qty | Tax | Amount | Verdict | Need |
|---|---|---|---|---|---|---|---|
${rows.join("\n")}

Total ${yen(spec.totalMinor)} (tax inside: ${spec.taxByRate.map((t) => `${t.rateBp / 100}% ${yen(t.taxMinor)}`).join(", ")}). Nine lines are fundable, two are rejected (beer: alcohol, gift card).

## Against the demo pledges

Fixed scenario rates EUR->JPY 162.35 and USD->JPY 151.20, holds EUR 20 water, USD 30 diapers, JPY 3,000 batteries, company match 1:1 (so the cap per need is twice the donor's pledge).

| Need | Credited qty | Fundable amount | Donor pledge | Cap (2x) | Within cap |
|---|---|---|---|---|---|
${needs.join("\n")}
`;
}

async function main() {
  const outRoot = arg("out") ? path.resolve(arg("out")!) : path.join(ROOT, "eval/receipts");
  const wanted = arg("set") ?? "all";
  const only = arg("only");
  const pool = wanted === "holdout" ? buildHoldout() : wanted === "holdout2" ? buildHoldout2() : allSpecs();
  const specs = pool.filter((s) => (wanted === "all" || s.set === wanted) && (!only || s.id === only));
  if (!specs.length) throw new Error("no receipts match");

  const browser = await chromium.launch();
  const page = await browser.newPage({ deviceScaleFactor: 1 });
  try {
    for (const spec of specs) {
      const { png, size, boxes } = await render(page, spec);
      const dir = path.join(outRoot, spec.set);
      await mkdir(dir, { recursive: true });
      const file = `${spec.id}.png`;
      await writeFile(path.join(dir, file), png);
      const receipt = specToReceipt(spec, boxes);
      const truth = Truth.parse({
        id: spec.id,
        set: spec.set,
        locale: spec.locale,
        seed: spec.seed,
        driveId: spec.set === "florida" ? FLORIDA.driveId : SCENARIOS[spec.locale].drive.id,
        image: { file, sha256: createHash("sha256").update(png).digest("hex"), mediaType: "image/png", width: size.width, height: size.height },
        receipt,
        labels: specToClassifications(spec),
        expect: spec.expect,
        spec,
      });
      await writeFile(path.join(dir, `${spec.id}.truth.json`), JSON.stringify(truth, null, 1) + "\n");
      if (spec.set === "hero") await writeFile(path.join(dir, "README.md"), heroReadme(spec));
      console.log(`${spec.id}  ${size.width}x${size.height}  ${(png.length / 1024).toFixed(0)} KB`);
    }
  } finally {
    await browser.close();
  }

  if (!arg("out")) await writeRecordings(outRoot);
}

/** Rebuilds recorded.json from every truth file: the recorded reader's answers are the ground truth. */
async function writeRecordings(root: string) {
  const rec: Recordings = { readings: {}, classifications: {} };
  for (const set of await readdir(root, { withFileTypes: true })) {
    if (!set.isDirectory() || set.name === "holdout" || set.name === "holdout2") continue;
    for (const f of (await readdir(path.join(root, set.name))).filter((n) => n.endsWith(".truth.json")).sort()) {
      const t = Truth.parse(JSON.parse(await readFile(path.join(root, set.name, f), "utf8")));
      rec.readings[t.image.sha256] = t.receipt;
      rec.classifications[receiptKey(t.receipt)] = t.labels;
    }
  }
  await writeFile(path.join(root, "recorded.json"), JSON.stringify(rec) + "\n");
  console.log(`recorded.json: ${Object.keys(rec.readings).length} readings`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
